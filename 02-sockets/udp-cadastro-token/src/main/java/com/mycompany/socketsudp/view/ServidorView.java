    private void iniciarServidor() {
        RecebedorUDP recebedor = new RecebedorUDP();
        log("Servidor ativo à espera do cliente na porta 1234");

        //aguarda um pacote datagrama chegar de um cliente
        DatagramPacket pacote = recebedor.recebe();

        while (pacote != null) {
            //monta uma string com os dados (bytes) que vieram no pacote
            String mensagem = new String(pacote.getData(), 0, pacote.getLength());
            log("Recebi " + mensagem + " de " + pacote.getAddress().getHostAddress() + ":" + pacote.getPort());

            // Separa a mensagem com ;
            String[] partes = mensagem.split(";");
            String resposta;

            if (partes[0].equals("CADASTRAR")) {
                Pessoa pessoa = new Pessoa(partes[1], partes[2]);

                if (controller.cadastrar(pessoa)) {
                    resposta = "OK";
                    log("Cadastrado: " + pessoa.getNome());
                } else {
                    resposta = "DUPLICADO";
                    log("Cadastro duplicado: " + pessoa.getEmail());
                }

            } else if (partes[0].equals("TOKEN")) {
                Pessoa pessoa = controller.buscarPorEmail(partes[1]);

                if (pessoa == null) {
                    resposta = "NAO_CADASTRADO";
                } else {
                    resposta = controller.gerarToken(pessoa);
                    log("Token de " + pessoa.getEmail() + ": " + resposta);
                }

            } else {
                resposta = "ERRO";
            }

            // Envia a resposta de volta para quem mandou
            recebedor.responde(resposta, pacote);

            // Atualiza a listagem de pessoas na interface do servidor
            atualizarListaGrafica();

            //aguarda o próximo pacote
            pacote = recebedor.recebe();
        }
    }

    private void log(final String msg) {
        SwingUtilities.invokeLater(new Runnable() {
            @Override
            public void run() {
                txtLog.append(msg + "\n");
            }
        });
    }

    private void atualizarListaGrafica() {
        SwingUtilities.invokeLater(new Runnable() {
            @Override
            public void run() {
                modelLista.clear();
                for (Pessoa p : controller.getListaPessoas()) {
                    modelLista.addElement(p.toString());
                }
            }
        });
    }

