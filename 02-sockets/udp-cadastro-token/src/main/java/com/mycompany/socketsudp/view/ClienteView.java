    private void btnEnviarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEnviarActionPerformed
        final String nome = txtNome.getText().trim();
        final String email = txtEmail.getText().trim();

        if (nome.isEmpty() || email.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Preencha o Nome e o E-mail!",
                "Aviso",
                JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        new Thread(new Runnable() {
            @Override
            public void run() {
                // Envia o cadastro e espera a resposta
                final String resposta = enviador.enviaEEspera("CADASTRAR;" + nome + ";" + email);

                SwingUtilities.invokeLater(new Runnable() {
                    @Override
                    public void run() {
                        if (resposta == null) {
                            JOptionPane.showMessageDialog(ClienteView.this,
                                "O servidor não respondeu!",
                                "Erro de Conexão",
                                JOptionPane.ERROR_MESSAGE);
                        } else if (resposta.equals("OK")) {
                            emailCadastrado = email;
                            btnEnviar.setEnabled(false);
                            JOptionPane.showMessageDialog(ClienteView.this,
                                "Cadastrado com sucesso!",
                                "Sucesso",
                                JOptionPane.INFORMATION_MESSAGE);
                            iniciarPedidoDeToken();
                        } else {
                            JOptionPane.showMessageDialog(ClienteView.this,
                                "Este e-mail já está cadastrado!",
                                "Aviso",
                                JOptionPane.WARNING_MESSAGE);
                        }
                    }
                });
            }
        }).start();
    }//GEN-LAST:event_btnEnviarActionPerformed

