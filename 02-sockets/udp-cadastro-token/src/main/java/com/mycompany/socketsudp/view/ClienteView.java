    // Thread que pede o token ao servidor a cada 10 segundos
    private void iniciarPedidoDeToken() {
        new Thread(new Runnable() {
            @Override
            public void run() {
                while (true) {
                    final String token = enviador.enviaEEspera("TOKEN;" + emailCadastrado);

                    SwingUtilities.invokeLater(new Runnable() {
                        @Override
                        public void run() {
                            if (token != null) {
                                txtToken.setText(token);
                            } else {
                                txtToken.setText("Servidor não respondeu");
                            }
                        }
                    });

                    try {
                        Thread.sleep(10000);
                    } catch (Exception e) {

                    }
                }
            }
        }).start();
    }

