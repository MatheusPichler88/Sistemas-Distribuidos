    private void iniciarServidor() {
            try {
                int porta = 50000;
                ServerSocket servidor = new ServerSocket(porta);
                log("Servidor ouvindo a porta: " + porta);

                //Loop para aceitar conexões contínuas
                while (true) {
                    final Socket cliente = servidor.accept();
                    log("Cliente conectado no IP: " + cliente.getInetAddress().getHostAddress());

                    // Trata o atendimento do cliente em uma Thread separada
                    new Thread(new Runnable() {
                        @Override
                        public void run() {
                            atenderCliente(cliente);
                        }
                    }).start();
                }
            } catch (Exception e) {
                log("Erro no servidor: " + e.getMessage());
            }
        }

    private void atenderCliente(Socket cliente) {
            try {
                // Prepara a saída dos dados, convertendo objetos em bytes
                ObjectOutputStream saida = new ObjectOutputStream(cliente.getOutputStream());
                saida.flush();

                // Prepara a entrada para receber os objetos vindos do cliente
                ObjectInputStream entrada = new ObjectInputStream(cliente.getInputStream());

                // Desserializa o objeto recebido do cliente
                Pessoa pRecebida = (Pessoa) entrada.readObject();
                log("Recebido do cliente: " + pRecebida.getNome());

                // Recebe o objeto e envia para as regras de negócio no controller
                Pessoa pProcessada = controller.processarCadastro(pRecebida);

                // Envia o objeto processado de volta para o cliente
                saida.writeObject(pProcessada);
                saida.flush();

                // Atualiza a listagem de pessoas na interface do servidor
                atualizarListaGrafica();

                // Fecha os fluxos de dados e a conexão com o cliente
                saida.close();
                entrada.close();
                cliente.close();

            } catch (Exception e) {
                log("Erro ao atender cliente: " + e.getMessage());
            }
        }

        private void log(final String msg) {
            SwingUtilities.invokeLater(new Runnable() {
                @Override
                public void run() {
                    txtLog.append(msg + "\n");
                }
            });
        }

        private void atualizarListaGrafica() {
            SwingUtilities.invokeLater(new Runnable() {
                @Override
                public void run() {
                    modelLista.clear();
                    for (Pessoa p : controller.getListaPessoas()) {
                        modelLista.addElement(p.toString());
                    }
                }
            });
        }

